-- 1. Speaking trong bài thi thử: bài nói ghi âm lúc thi gắn với lượt thi, giống writing_submissions.attempt_id.
ALTER TABLE speaking_submissions ADD COLUMN attempt_id BIGINT;
ALTER TABLE speaking_submissions ADD CONSTRAINT fk_speaking_submissions_attempt
  FOREIGN KEY (attempt_id) REFERENCES test_attempts (id);
CREATE INDEX ix_speaking_submissions_attempt ON speaking_submissions (attempt_id);

-- 2. Ngân hàng cụm từ Writing: từ nối, mở bài, mô tả xu hướng... nạp từ content/phrases.json.
CREATE TABLE writing_phrases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- TASK1 | TASK2 | BOTH: Task 1 cần mô tả số liệu, Task 2 cần lập luận.
  task VARCHAR(10) NOT NULL,
  category VARCHAR(60) NOT NULL,
  phrase VARCHAR(255) NOT NULL,
  meaning_vi VARCHAR(255) NOT NULL,
  example VARCHAR NOT NULL,
  -- Band tối thiểu nên dùng: cụm từ quá cao so với trình độ dễ dùng sai.
  band_min DOUBLE PRECISION,
  sort_order INTEGER NOT NULL,
  CONSTRAINT uk_writing_phrases UNIQUE (category, phrase)
);
