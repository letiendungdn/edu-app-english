FROM reading_questions;

INSERT INTO question_groups (owner_type, owner_id, question_type, instruction, sort_order)
SELECT DISTINCT 'LISTENING_TRACK', track_id, 'MULTIPLE_CHOICE', 'Choose the correct letter, A, B, C or D.', 1
FROM listening_questions;

INSERT INTO questions (group_id, number, prompt, accepted_answers, explanation, legacy_id)
SELECT g.id,
       ROW_NUMBER() OVER (PARTITION BY q.passage_id ORDER BY q.sort_order, q.id),
       q.question,
       '["' || COALESCE((
         SELECT CASE o.sort_order WHEN 1 THEN 'A' WHEN 2 THEN 'B' WHEN 3 THEN 'C' WHEN 4 THEN 'D'
                                  WHEN 5 THEN 'E' WHEN 6 THEN 'F' ELSE 'G' END
         FROM reading_options o
         WHERE o.question_id = q.id AND o.text = q.answer
         ORDER BY o.sort_order FETCH FIRST 1 ROWS ONLY), 'A') || '"]',
       q.explanation,
       q.id
FROM reading_questions q
JOIN question_groups g ON g.owner_type = 'READING_PASSAGE' AND g.owner_id = q.passage_id;

INSERT INTO question_options (question_id, option_key, text, sort_order)
SELECT nq.id,
       CASE o.sort_order WHEN 1 THEN 'A' WHEN 2 THEN 'B' WHEN 3 THEN 'C' WHEN 4 THEN 'D'
                         WHEN 5 THEN 'E' WHEN 6 THEN 'F' ELSE 'G' END,
       o.text,
       o.sort_order
FROM reading_options o
JOIN questions nq ON nq.legacy_id = o.question_id
JOIN question_groups g ON g.id = nq.group_id AND g.owner_type = 'READING_PASSAGE';

UPDATE questions SET legacy_id = NULL;

INSERT INTO questions (group_id, number, prompt, accepted_answers, explanation, legacy_id)
SELECT g.id,
       ROW_NUMBER() OVER (PARTITION BY q.track_id ORDER BY q.sort_order, q.id),
       q.question,
       '["' || COALESCE((
         SELECT CASE o.sort_order WHEN 1 THEN 'A' WHEN 2 THEN 'B' WHEN 3 THEN 'C' WHEN 4 THEN 'D'
                                  WHEN 5 THEN 'E' WHEN 6 THEN 'F' ELSE 'G' END
         FROM listening_options o
         WHERE o.question_id = q.id AND o.text = q.answer
         ORDER BY o.sort_order FETCH FIRST 1 ROWS ONLY), 'A') || '"]',
       q.explanation,
       q.id
FROM listening_questions q
JOIN question_groups g ON g.owner_type = 'LISTENING_TRACK' AND g.owner_id = q.track_id;

INSERT INTO question_options (question_id, option_key, text, sort_order)
SELECT nq.id,
       CASE o.sort_order WHEN 1 THEN 'A' WHEN 2 THEN 'B' WHEN 3 THEN 'C' WHEN 4 THEN 'D'
                         WHEN 5 THEN 'E' WHEN 6 THEN 'F' ELSE 'G' END,
       o.text,
       o.sort_order
FROM listening_options o
JOIN questions nq ON nq.legacy_id = o.question_id
