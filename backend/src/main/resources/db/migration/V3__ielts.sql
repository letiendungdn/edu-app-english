-- 5. Writing ------------------------------------------------------------------

CREATE TABLE writing_prompts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module VARCHAR(20) NOT NULL,
  task VARCHAR(10) NOT NULL,
  task_kind VARCHAR(40) NOT NULL,
  title VARCHAR(255) NOT NULL,
  prompt VARCHAR NOT NULL,
  -- Dữ liệu biểu đồ Task 1 dạng JSON, frontend tự vẽ. NULL với bài viết thư hoặc Task 2.
  chart_data VARCHAR,
  image_url VARCHAR(500),
  min_words INTEGER NOT NULL,
  topic VARCHAR(255),
  sample_answer VARCHAR,
  sample_band DOUBLE PRECISION,
  sort_order INTEGER NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE writing_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  prompt_id BIGINT NOT NULL,
  attempt_id BIGINT,
  text VARCHAR NOT NULL,
  word_count INTEGER NOT NULL,
  time_spent_sec INTEGER,
  status VARCHAR(20) NOT NULL,
  score_ta DOUBLE PRECISION,
  score_cc DOUBLE PRECISION,
  score_lr DOUBLE PRECISION,
  score_gra DOUBLE PRECISION,
  band DOUBLE PRECISION,
  feedback VARCHAR,
  error VARCHAR,
  grader VARCHAR(20),
  created_at TIMESTAMP WITH TIME ZONE,
  graded_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_writing_submissions_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_writing_submissions_prompt FOREIGN KEY (prompt_id) REFERENCES writing_prompts (id)
);
CREATE INDEX ix_writing_submissions_user ON writing_submissions (user_id, created_at);

-- 6. Speaking -----------------------------------------------------------------

CREATE TABLE speaking_prompts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part INTEGER NOT NULL,
  topic VARCHAR(255) NOT NULL,
  question VARCHAR NOT NULL,
  -- Part 2: các gạch đầu dòng "You should say", mảng JSON.
  cue_card_points VARCHAR,
  sort_order INTEGER NOT NULL
);

CREATE TABLE speaking_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  prompt_id BIGINT NOT NULL,
  audio_path VARCHAR(500),
  transcript VARCHAR,
  duration_sec INTEGER,
  status VARCHAR(20) NOT NULL,
  score_fc DOUBLE PRECISION,
  score_lr DOUBLE PRECISION,
  score_gra DOUBLE PRECISION,
  score_p DOUBLE PRECISION,
  band DOUBLE PRECISION,
  feedback VARCHAR,
  error VARCHAR,
  created_at TIMESTAMP WITH TIME ZONE,
  graded_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_speaking_submissions_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_speaking_submissions_prompt FOREIGN KEY (prompt_id) REFERENCES speaking_prompts (id)
);
CREATE INDEX ix_speaking_submissions_user ON speaking_submissions (user_id, created_at);

-- 7. Bài thi: placement, mock, luyện một phần ---------------------------------------

CREATE TABLE ielts_tests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(20) NOT NULL,
  module VARCHAR(20) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description VARCHAR,
  duration_min INTEGER NOT NULL,
  published BOOLEAN NOT NULL,
  sort_order INTEGER NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE test_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_id BIGINT NOT NULL,
  skill VARCHAR(20) NOT NULL,
  ref_type VARCHAR(30) NOT NULL,
  ref_id BIGINT NOT NULL,
  sort_order INTEGER NOT NULL,
  CONSTRAINT fk_test_sections_test FOREIGN KEY (test_id) REFERENCES ielts_tests (id)
);

CREATE TABLE test_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  test_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE,
  -- Bản nháp Writing trong lúc thi: JSON {promptId: text}.
  writing_drafts VARCHAR,
  raw_listening INTEGER,
  total_listening INTEGER,
  raw_reading INTEGER,
  total_reading INTEGER,
  band_listening DOUBLE PRECISION,
  band_reading DOUBLE PRECISION,
  band_writing DOUBLE PRECISION,
  band_speaking DOUBLE PRECISION,
  band_overall DOUBLE PRECISION,
  CONSTRAINT fk_test_attempts_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_test_attempts_test FOREIGN KEY (test_id) REFERENCES ielts_tests (id)
);
CREATE INDEX ix_test_attempts_user ON test_attempts (user_id, started_at);

CREATE TABLE attempt_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  given VARCHAR,
  points INTEGER,
  CONSTRAINT fk_attempt_answers_attempt FOREIGN KEY (attempt_id) REFERENCES test_attempts (id),
  CONSTRAINT fk_attempt_answers_question FOREIGN KEY (question_id) REFERENCES questions (id),
  CONSTRAINT uk_attempt_answers UNIQUE (attempt_id, question_id)
);

ALTER TABLE writing_submissions ADD CONSTRAINT fk_writing_submissions_attempt
  FOREIGN KEY (attempt_id) REFERENCES test_attempts (id);

-- 8. Lộ trình -------------------------------------------------------------------

CREATE TABLE roadmaps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  exam_date DATE,
  start_band DOUBLE PRECISION,
  target_band DOUBLE PRECISION NOT NULL,
  feasibility VARCHAR(20) NOT NULL,
  version INTEGER NOT NULL,
  generated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_roadmaps_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_roadmaps_user_status ON roadmaps (user_id, status);

CREATE TABLE roadmap_phases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roadmap_id BIGINT NOT NULL,
  kind VARCHAR(30) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  goal VARCHAR NOT NULL,
  sort_order INTEGER NOT NULL,
  CONSTRAINT fk_roadmap_phases_roadmap FOREIGN KEY (roadmap_id) REFERENCES roadmaps (id)
);

CREATE TABLE roadmap_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roadmap_id BIGINT NOT NULL,
  phase_id BIGINT NOT NULL,
  due_date DATE NOT NULL,
  type VARCHAR(30) NOT NULL,
  skill VARCHAR(20),
  ref_type VARCHAR(30),
  ref_id BIGINT,
  title VARCHAR(255) NOT NULL,
  estimated_min INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  completed_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_roadmap_tasks_roadmap FOREIGN KEY (roadmap_id) REFERENCES roadmaps (id),
  CONSTRAINT fk_roadmap_tasks_phase FOREIGN KEY (phase_id) REFERENCES roadmap_phases (id)
);
CREATE INDEX ix_roadmap_tasks_roadmap_due ON roadmap_tasks (roadmap_id, due_date);
