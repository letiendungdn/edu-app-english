-- Schema IELTS: hồ sơ, band, ngân hàng câu hỏi dùng chung, Writing, Speaking, bài thi, lộ trình.
-- Chạy được trên Postgres và H2 (MODE=PostgreSQL). Văn bản dài dùng VARCHAR không độ dài (xem V2).
-- Band lưu DOUBLE PRECISION: mọi giá trị là bội của 0.5 nên biểu diễn chính xác.

-- 1. Hồ sơ và band ------------------------------------------------------------

CREATE TABLE ielts_profiles (
  user_id BIGINT PRIMARY KEY,
  module VARCHAR(20) NOT NULL,
  current_band DOUBLE PRECISION,
  target_band DOUBLE PRECISION NOT NULL,
  exam_date DATE,
  daily_minutes INTEGER NOT NULL,
  study_days_per_week INTEGER NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE,
  updated_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_ielts_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE band_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  skill VARCHAR(20) NOT NULL,
  band DOUBLE PRECISION NOT NULL,
  source VARCHAR(20) NOT NULL,
  source_ref_id BIGINT,
  recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_band_records_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_band_records_user_skill ON band_records (user_id, skill, recorded_at);

-- Bảng quy đổi điểm thô /40 sang band. Để trong DB vì bảng chính thức có thể lệch nhẹ giữa các đề.
CREATE TABLE band_conversions (
