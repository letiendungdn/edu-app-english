-- 3. Ngân hàng câu hỏi dùng chung cho Reading và Listening ----------------------

CREATE TABLE question_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_type VARCHAR(30) NOT NULL,
  owner_id BIGINT NOT NULL,
  question_type VARCHAR(40) NOT NULL,
  instruction VARCHAR NOT NULL,
  word_limit INTEGER,
  image_url VARCHAR(500),
  sort_order INTEGER NOT NULL
);
CREATE INDEX ix_question_groups_owner ON question_groups (owner_type, owner_id);

-- Lựa chọn dùng chung cả nhóm: danh sách heading, sentence ending, feature...
CREATE TABLE question_group_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  option_key VARCHAR(10) NOT NULL,
  text VARCHAR NOT NULL,
  sort_order INTEGER NOT NULL,
  CONSTRAINT fk_question_group_options_group FOREIGN KEY (group_id) REFERENCES question_groups (id)
);

CREATE TABLE questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  number INTEGER NOT NULL,
  prompt VARCHAR NOT NULL,
  -- Mảng JSON các đáp án được chấp nhận, ví dụ ["1990","nineteen ninety"] hoặc ["B"].
  accepted_answers VARCHAR NOT NULL,
  explanation VARCHAR,
  evidence VARCHAR,
  legacy_id BIGINT,
  CONSTRAINT fk_questions_group FOREIGN KEY (group_id) REFERENCES question_groups (id)
);
CREATE INDEX ix_questions_group ON questions (group_id);

-- Lựa chọn riêng của từng câu (trắc nghiệm).
CREATE TABLE question_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL,
  option_key VARCHAR(10) NOT NULL,
  text VARCHAR NOT NULL,
  sort_order INTEGER NOT NULL,
  CONSTRAINT fk_question_options_question FOREIGN KEY (question_id) REFERENCES questions (id)
);

-- 4. Chuyển câu hỏi trắc nghiệm cũ sang bảng mới ---------------------------------
-- Mỗi bài cũ thành một nhóm MULTIPLE_CHOICE. Đáp án cũ lưu nguyên văn lựa chọn; bảng mới lưu chữ cái A, B, C...

