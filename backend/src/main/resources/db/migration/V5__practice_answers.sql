-- Câu trả lời từng câu của mọi lần chấm Reading/Listening (bài luyện, placement, thi thử).
-- Trước đây bài luyện chỉ lưu tổng điểm nên không biết người học sai câu nào, yếu dạng câu nào.
-- Bảng này phục vụ sổ lỗi sai và thống kê độ chính xác theo dạng câu hỏi IELTS.
-- question_type, skill sao chép từ nhóm câu lúc chấm để thống kê không cần join.

CREATE TABLE practice_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  question_type VARCHAR(40) NOT NULL,
  skill VARCHAR(20) NOT NULL,
  owner_type VARCHAR(30) NOT NULL,
  owner_id BIGINT NOT NULL,
  source VARCHAR(20) NOT NULL,
  source_ref_id BIGINT,
  given VARCHAR,
  points INTEGER NOT NULL,
  max_points INTEGER NOT NULL,
  answered_at TIMESTAMP WITH TIME ZONE NOT NULL,
  -- Người học bấm "Đã hiểu" trong sổ lỗi sai.
  reviewed_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_practice_answers_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_practice_answers_question FOREIGN KEY (question_id) REFERENCES questions (id)
);
CREATE INDEX ix_practice_answers_user_time ON practice_answers (user_id, answered_at);
CREATE INDEX ix_practice_answers_user_question ON practice_answers (user_id, question_id);

-- Chuyển câu trả lời của các bài thi đã nộp sang bảng mới để sổ lỗi sai có dữ liệu ngay.
INSERT INTO practice_answers (user_id, question_id, question_type, skill, owner_type, owner_id, source, source_ref_id,
                              given, points, max_points, answered_at)
SELECT t.user_id, a.question_id, g.question_type,
       CASE g.owner_type WHEN 'LISTENING_TRACK' THEN 'LISTENING' ELSE 'READING' END,
       g.owner_type, g.owner_id,
       CASE it.kind WHEN 'PLACEMENT' THEN 'PLACEMENT' ELSE 'MOCK' END,
       t.id, a.given, a.points,
       -- Chọn nhiều: mỗi đáp án đúng một điểm, đếm phần tử mảng JSON qua số dấu phẩy.
       CASE WHEN g.question_type = 'MULTIPLE_CHOICE_MULTI'
            THEN LENGTH(q.accepted_answers) - LENGTH(REPLACE(q.accepted_answers, ',', '')) + 1 ELSE 1 END,
       COALESCE(t.submitted_at, t.started_at)
FROM attempt_answers a
JOIN test_attempts t ON t.id = a.attempt_id AND t.status = 'SUBMITTED'
JOIN ielts_tests it ON it.id = t.test_id
JOIN questions q ON q.id = a.question_id
JOIN question_groups g ON g.id = q.group_id
WHERE a.points IS NOT NULL;
